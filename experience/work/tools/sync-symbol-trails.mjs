// Builds the reading experience's Symbol Trails from the card academy.
//
// Inputs:  website/src/lib/academy/leaves/NN.json   (one written leaf per card)
//          website/src/lib/academy/symbol-trails.json (which cards each trail follows, and its essays)
// Outputs: experience/work/olivia-product/symbol-trails-data.js (trail data + artwork hashes)
//          website/src/lib/academy/symbol-trails.ts            (symbol key → trail id, for card pages)
//
// Usage: node experience/work/tools/sync-symbol-trails.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const leavesDir = root + 'website/src/lib/academy/leaves/';
const leaves = new Map(readdirSync(leavesDir).filter(f => /^\d\d\.json$/.test(f)).map(f => {
  const leaf = JSON.parse(readFileSync(leavesDir + f, 'utf8'));
  return [leaf.id, leaf];
}));
const trails = JSON.parse(readFileSync(root + 'website/src/lib/academy/symbol-trails.json', 'utf8'));

const fail = message => { console.error(message); process.exit(1); };
const seenKeys = new Map();
const artwork = {};
const data = trails.map(trail => {
  for (const key of trail.keys) {
    if (seenKeys.has(key)) fail(`Symbol key "${key}" belongs to both ${seenKeys.get(key)} and ${trail.id}.`);
    seenKeys.set(key, trail.id);
  }
  if (!trail.group?.en?.trim() || !trail.group?.uk?.trim()) fail(`${trail.id}: group needs en and uk names.`);
  for (const lang of ['en', 'uk']) for (const field of ['name', 'title', 'introduction', 'comparison', 'prompt']) {
    if (!trail[lang]?.[field]?.trim()) fail(`${trail.id}.${lang}.${field} is empty.`);
  }
  const cards = trail.cards.map(({ id, symbol }) => {
    const leaf = leaves.get(id);
    if (!leaf) fail(`${trail.id}: no leaf for card ${id}.`);
    const entry = leaf.symbols[symbol];
    if (!entry) fail(`${trail.id}: card ${id} has no symbol #${symbol}.`);
    if (!trail.keys.includes(entry.key)) fail(`${trail.id}: card ${id} symbol #${symbol} is "${entry.key}", not one of ${trail.keys.join(', ')}.`);
    artwork[id] = { file: leaf.artwork.file, sha256: leaf.artwork.sha256 };
    return { cardId: id, slug: leaf.slug, x: entry.x, y: entry.y, en: entry.en, uk: entry.uk };
  });
  if (new Set(cards.map(card => card.cardId)).size !== cards.length) fail(`${trail.id}: a card appears twice.`);
  return { id: trail.id, group: trail.group, en: trail.en, uk: trail.uk, cards };
});

const sorted = Object.fromEntries(Object.entries(artwork).sort((a, b) => a[0] - b[0]));
writeFileSync(root + 'experience/work/olivia-product/symbol-trails-data.js',
  `// Generated by experience/work/tools/sync-symbol-trails.mjs from the card academy. Do not edit by hand.\n` +
  `export const SYMBOL_TRAIL_DATA = ${JSON.stringify(data, null, 1)};\n\n` +
  `export const SYMBOL_ARTWORK = ${JSON.stringify(sorted, null, 1)};\n`);

const map = Object.fromEntries([...seenKeys].sort());
const ts = readFileSync(root + 'website/src/lib/academy/symbol-trails.ts', 'utf8')
  .replace(/export const SYMBOL_TRAIL_OF: Record<string, string> = [^;]*;/, `export const SYMBOL_TRAIL_OF: Record<string, string> = ${JSON.stringify(map, null, 2)};`);
writeFileSync(root + 'website/src/lib/academy/symbol-trails.ts', ts);
console.log(`${data.length} trails, ${Object.keys(sorted).length} cards, ${seenKeys.size} symbol keys`);
