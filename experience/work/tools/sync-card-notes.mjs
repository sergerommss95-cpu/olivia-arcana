// Copy the product's curated card notes (EN and UK) into the website, where the
// AI reading service and the Ukrainian card pages read them.
// Run after editing content.js, minor-content.js, minor-reversed.js or card-notes-uk.js:
//   node experience/work/tools/sync-card-notes.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const product = path.join(here, '../olivia-product');
const { CARD_NOTES, REVERSED_NOTES } = await import(path.join(product, 'content.js'));
const { UK_NOTES } = await import(path.join(product, 'card-notes-uk.js'));
const { TAROT_CARDS } = await import(path.join(product, 'deck-catalog.js'));

const side = note => ({ meaning: note.meaning, prompt: note.prompt, practice: note.practice });
const notes = { en: {}, uk: {} };
TAROT_CARDS.forEach((card, id) => {
  notes.en[card.name] = { upright: side(CARD_NOTES[id]), reversed: side({ ...CARD_NOTES[id], ...REVERSED_NOTES[id] }), learn: CARD_NOTES[id].learn };
  notes.uk[card.name] = { upright: side(UK_NOTES[id]), reversed: side(UK_NOTES[id].reversed), learn: UK_NOTES[id].learn };
});
if (Object.keys(notes.en).length !== 78 || Object.keys(notes.uk).length !== 78) throw new Error('Expected 78 cards in each language.');

const out = `// Generated by experience/work/tools/sync-card-notes.mjs from the product's curated
// card notes. Do not edit by hand: edit the product source and run the script.
export type CardNoteSide = { meaning: string; prompt: string; practice: string };
export type CardNote = { upright: CardNoteSide; reversed: CardNoteSide; learn: string };

export const TAROT_NOTES: Record<"en" | "uk", Record<string, CardNote>> = ${JSON.stringify(notes, null, 1)};
`;
const target = path.join(here, '../../../website/src/lib/academy/tarot-notes.ts');
fs.writeFileSync(target, out);
console.log('Wrote', path.relative(process.cwd(), target), Math.round(out.length / 1024), 'KB');
