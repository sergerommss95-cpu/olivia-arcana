// website/scripts/card-names.mjs
// Regenerates the card-name table in src/lib/card-names.js (between its
// "generated" markers) from the deck of record: ALL_CARDS order and names,
// TAROT_UK for Ukrainian. The browser gets these 78 names, not the library.
//
//   NODE_OPTIONS="--disable-warning=MODULE_TYPELESS_PACKAGE_JSON" node scripts/card-names.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ALL_CARDS } from "../src/lib/academy/tarot-cards.ts";
import { TAROT_UK } from "../src/lib/academy/tarot-cards-uk.ts";

const target = fileURLToPath(new URL("../src/lib/card-names.js", import.meta.url));
const cards = fileURLToPath(new URL("../public/cards/", import.meta.url));

// The same stem as getCardImagePath(): "00_the_fool".
const rows = ALL_CARDS.map((card, i) => {
  const stem = `${String(i).padStart(2, "0")}_${card.name.toLowerCase().replace(/\s+/g, "_")}`;
  if (!existsSync(`${cards}${stem}.webp`)) throw new Error(`No art for ${stem}`);
  const uk = TAROT_UK[card.name]?.name;
  if (!uk) throw new Error(`No Ukrainian name for ${card.name}`);
  return `  ${JSON.stringify(stem)}: { en: ${JSON.stringify(card.name)}, uk: ${JSON.stringify(uk)} },`;
});

const BEGIN = "// BEGIN generated by scripts/card-names.mjs";
const END = "// END generated";
const source = readFileSync(target, "utf8");
const from = source.indexOf(BEGIN);
const to = source.indexOf(END);
if (from < 0 || to < from) throw new Error("card-names.js has lost its generated markers");
const table = [BEGIN, "export const CARD_NAMES = {", ...rows, "};", ""].join("\n");
writeFileSync(target, source.slice(0, from) + table + source.slice(to));
console.log(`${rows.length} card names written to src/lib/card-names.js`);
