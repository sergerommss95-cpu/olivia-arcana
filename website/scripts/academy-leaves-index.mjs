// Regenerates the index.ts beside each folder of JSON content (card leaves,
// lessons, worked readings) so pages can import every file statically.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const folders = [
  { dir: "../src/lib/academy/leaves/", pattern: /^\d\d\.json$/, name: "LEAF_FILES" },
  { dir: "../src/lib/learn/lessons/", pattern: /^[a-z0-9-]+\.json$/, name: "LESSON_FILES" },
  { dir: "../src/lib/learn/worked-readings/", pattern: /^[a-z0-9-]+\.json$/, name: "WORKED_READING_FILES" },
];

for (const { dir, pattern, name } of folders) {
  const path = fileURLToPath(new URL(dir, import.meta.url));
  if (!existsSync(path)) mkdirSync(path, { recursive: true });
  const files = readdirSync(path).filter((f) => pattern.test(f)).sort();
  const id = (f) => "file_" + f.replace(/\.json$/, "").replace(/[^a-z0-9]/gi, "_");
  const lines = [
    "// Generated by scripts/academy-leaves-index.mjs. Do not edit by hand.",
    ...files.map((f) => `import ${id(f)} from "./${f}";`),
    "",
    `export const ${name} = [${files.map(id).join(", ")}];`,
    "",
  ];
  writeFileSync(path + "index.ts", lines.join("\n"));
  console.log(`${files.length} files indexed in ${dir}`);
}

// A compact map of each card's rarer carved symbols (with pin positions), for
// the spread survey's "shared symbol" line in the reading experience.
import { readFileSync } from "node:fs";
import { COMMON_SYMBOL_KEYS } from "../src/lib/learn/card-facts.js";
const leavesDir = fileURLToPath(new URL("../src/lib/academy/leaves/", import.meta.url));
const symbols = {};
for (const file of readdirSync(leavesDir).filter((f) => /^\d\d\.json$/.test(f)).sort()) {
  const leaf = JSON.parse(readFileSync(leavesDir + file, "utf8"));
  symbols[leaf.id] = leaf.symbols.filter((s) => !COMMON_SYMBOL_KEYS.has(s.key) && s.en && s.uk).map((s) => ({ k: s.key, x: s.x, y: s.y, en: s.en.name, uk: s.uk.name }));
}
writeFileSync(fileURLToPath(new URL("../src/lib/learn/card-symbols.json", import.meta.url)), JSON.stringify(symbols) + "\n");
console.log(`card symbols written for ${Object.keys(symbols).length} cards`);
