/**
 * Card art file → card name, for the name plate that follows the reader's
 * pointer and focus (components/CardNameHover.tsx). Only the 78 names reach
 * the browser, not the card library.
 *
 * Recognised art: /cards/NN_slug.webp and its thumbs/, mid/ and wheel/ cuts,
 * /cards-portal/NN_slug.webp, and the reading experience's hashed decks
 * (/experience/assets/NN-slug.<hash>.webp, amielle-v1-NN…, space-between-NN…).
 * NN is the card's place in ALL_CARDS (0–77). Card backs are never a card.
 */

const FACE = /\/cards(?:-portal)?\/(?:thumbs\/|mid\/|wheel\/)?(\d\d_[a-z_]+)\.(?:webp|png|jpe?g|avif)\b/;
const DECKS = /\/experience\/assets\/(?:(\d\d-[a-z-]+?)(?:-phone)?|(?:amielle-v1|space-between)-(\d\d)(?:-(?:men|women))?)\.[0-9a-f]{8,}\.webp\b/;
const BACK = /\/cards\/back[\w-]*\.\w+\b|\/experience\/assets\/(?:card-back|space-between-back)\.[0-9a-f]{8,}\.webp\b/;

const ROMAN = "0 I II III IV V VI VII VIII IX X XI XII XIII XIV XV XVI XVII XVIII XIX XX XXI".split(" ");

/** True when the file is a card back (a face-down card). */
export function isCardBack(src) {
  return BACK.test(src || "");
}

/**
 * The card a file shows: { id, numeral, en, uk } (numeral only for the 22
 * Majors, "" otherwise), or null for anything that is not a card face.
 */
export function cardFromSrc(src) {
  if (!src || BACK.test(src)) return null;
  let stem = FACE.exec(src)?.[1];
  if (!stem) {
    const deck = DECKS.exec(src);
    if (!deck) return null;
    stem = deck[1] ? deck[1].replace(/-/g, "_") : Object.keys(CARD_NAMES)[Number(deck[2])];
  }
  const names = stem && CARD_NAMES[stem];
  if (!names) return null;
  const id = Number(stem.slice(0, 2));
  return { id, numeral: id < 22 ? ROMAN[id] : "", en: names.en, uk: names.uk };
}

